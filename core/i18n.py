UK_EXACT = {v: k for k, v in EN_EXACT.items()}

def _clean_linux_emoji(txt):
    import sys
    if not sys.platform.startswith("linux"):
        return txt
    return re.sub(r"[\U0001F300-\U0001FAFF\u2600-\u27BF\uFE0F]+\s*", "", txt)

def tr(text, lang="en"):
    if not text:
        return text
    s = _clean_linux_emoji(str(text))
    if lang == "uk":
        if s in UK_EXACT:
            return UK_EXACT[s]
        for uk, en in sorted(EN_SUBSTR, key=lambda x: len(x[1]), reverse=True):
            if len(en) >= 3 and en in s:
                s = s.replace(en, uk)
        return s
    if s in EN_EXACT:
        return EN_EXACT[s]
    for uk, en in EN_SUBSTR:
        if uk in s:
            s = s.replace(uk, en)
    s = re.sub(r"(\d+)\s*хв\s*([\d.]+)\s*с", r"\1m \2s", s)
    s = re.sub(r"(?<=\d)\s*с(?=\b|\)|\.)", " s", s)
    s = re.sub(r"\bза\s+(?=\d)", "in ", s)
    s = re.sub(r"\bіз\s+(?=\d)", "of ", s)
    s = re.sub(r"\bо\s+(?=\d{2}:\d{2})", "at ", s)
    return s

def apply_widget_i18n(widget, lang="en"):
    try:
        if "text" in widget.keys():
            raw_cur = widget.cget("text")
            cur = str(raw_cur) if raw_cur is not None else ""
            if cur.strip():
                t_val = tr(cur, lang)
                if t_val != cur:
                    widget.configure(text=t_val)
    except Exception:
        pass
    try:
        for ch in widget.winfo_children():
            apply_widget_i18n(ch, lang)
    except Exception:
        pass
